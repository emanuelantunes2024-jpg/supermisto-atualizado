let uid = 0;
const next = () => `r${++uid}`;

function receta({
  nombre,
  categoria,
  descripcion,
  imagen,
  tiempoMinutos,
  dificultad,
  rendimientoBase,
  unidadRendimiento,
  ingredientes,
  pasos,
  costosExtra = 0,
  margenSugerido = 70,
  paraVender = false,
  novedad = false,
  publicada = true,
  consejos = [],
  conservacion = 'Conservar en recipiente hermético en un lugar fresco y seco.',
}) {
  return {
    id: next(),
    slug: nombre
      .toLowerCase()
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, ''),
    nombre,
    categoria,
    descripcion,
    imagen,
    tiempoMinutos,
    dificultad,
    rendimientoBase,
    unidadRendimiento,
    ingredientes,
    pasos,
    consejos,
    conservacion,
    costosExtra,
    margenSugerido,
    paraVender,
    novedad,
    publicada,
    creadoEn: '2026-08-01',
  };
}

